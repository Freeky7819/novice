"""Export trusted YAML/style to a static Worker module. No network or secrets."""
import argparse
import json
from pathlib import Path
import yaml
from fetch import public_config, save
from summarize import article_instructions

ROOT = Path(__file__).resolve().parent


def generated(root=ROOT):
    ai = yaml.safe_load((root/'config/ai.yaml').read_text(encoding='utf-8'))
    topics = yaml.safe_load((root/'config/topics.yaml').read_text(encoding='utf-8'))
    allowed = [t['id'] for t in topics['topics']]
    style = (root/'config/style.md').read_text(encoding='utf-8')[:12000]
    value = {'model': ai['models']['anthropic'], 'max_tokens': ai['max_output_tokens'],
             'topics': allowed, 'exclude_keywords': topics.get('exclude_keywords', []),
             'system': article_instructions(style, allowed)}
    return '// Generated by prepare_worker.py; edit config/ instead.\nexport default ' + json.dumps(value, ensure_ascii=False, indent=2) + ';\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'worker/generated.js'
    content = generated()
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit('Worker config is stale; run python prepare_worker.py')
    else:
        path.parent.mkdir(exist_ok=True)
        path.write_text(content, encoding='utf-8')
        sources = yaml.safe_load((ROOT/'config/sources.yaml').read_text(encoding='utf-8'))['sources']
        topics = yaml.safe_load((ROOT/'config/topics.yaml').read_text(encoding='utf-8'))
        ai = yaml.safe_load((ROOT/'config/ai.yaml').read_text(encoding='utf-8'))
        save(ROOT/'data/config.json', public_config(sources, topics, ai))


if __name__ == '__main__':
    main()
